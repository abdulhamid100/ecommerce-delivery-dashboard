"""Compute the dashboard's key numbers in pandas, to cross-check the Power BI report.

Every value here is calculated the same way as the matching DAX measure in powerbi/measures.dax,
so the numbers on each card and chart in Power BI should match this file exactly (no filters applied).

Writes: powerbi/reference_numbers.md and the preview charts in images/.
Run:    python analysis/reference_numbers.py   (after prepare_data.py)
"""
from pathlib import Path

import matplotlib.pyplot as plt
import matplotlib.ticker as mtick
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
MODEL, IMG = ROOT / "data" / "model", ROOT / "images"
IMG.mkdir(exist_ok=True)

orders = pd.read_csv(MODEL / "fact_orders.csv", parse_dates=["purchase_date"])
items = pd.read_csv(MODEL / "fact_order_items.csv")
states = pd.read_csv(MODEL / "dim_states.csv")

# ---- Measures (same logic as measures.dax) ---------------------------------------------
def kpis(df):
    reviewed = df.review_score.dropna()
    shipped = df.seller_shipped_late.dropna()
    return pd.Series({
        "Delivered Orders": len(df),
        "Late Orders": int(df.is_late.sum()),
        "Late Delivery Rate": df.is_late.mean(),
        "On-Time Rate": 1 - df.is_late.mean(),
        "Avg Review Score": reviewed.mean(),
        "Avg Score On Time": df.loc[df.is_late == 0, "review_score"].mean(),
        "Avg Score Late": df.loc[df.is_late == 1, "review_score"].mean(),
        "Negative Review Rate": (reviewed <= 2).mean(),
        "Negative Review Rate On Time": (df.loc[df.is_late == 0, "review_score"].dropna() <= 2).mean(),
        "Negative Review Rate Late": (df.loc[df.is_late == 1, "review_score"].dropna() <= 2).mean(),
        "Avg Delivery Days": df.delivery_days.mean(),
        "Avg Days Early vs Estimate": -df.days_vs_estimate.mean(),
        "Seller Late Shipment Rate": shipped.mean(),
        "Late Rate (Seller Shipped Late)": df.loc[df.seller_shipped_late == 1, "is_late"].mean(),
        "Late Rate (Seller Shipped On Time)": df.loc[df.seller_shipped_late == 0, "is_late"].mean(),
    })

k = kpis(orders)
revenue = items.price.sum()

pct = {"Late Delivery Rate", "On-Time Rate", "Negative Review Rate", "Negative Review Rate On Time",
       "Negative Review Rate Late", "Seller Late Shipment Rate", "Late Rate (Seller Shipped Late)",
       "Late Rate (Seller Shipped On Time)"}
def fmt(name, v):
    if name in pct: return f"{v:.1%}"
    if name in ("Delivered Orders", "Late Orders"): return f"{int(v):,}"
    return f"{v:.2f}"

by_bucket = (orders.groupby(["delivery_bucket_sort", "delivery_bucket"])
             .agg(orders=("order_id", "size"), avg_score=("review_score", "mean"),
                  negative_rate=("review_score", lambda s: (s.dropna() <= 2).mean()))
             .reset_index(level=0, drop=True))

orders["month"] = orders.purchase_date.dt.to_period("M")
by_month = orders.groupby("month").agg(orders=("order_id", "size"), late_rate=("is_late", "mean"),
                                       avg_score=("review_score", "mean"))

by_state = (orders.groupby("customer_state")
            .agg(orders=("order_id", "size"), late_orders=("is_late", "sum"), late_rate=("is_late", "mean"),
                 avg_delivery_days=("delivery_days", "mean"), avg_score=("review_score", "mean"))
            .join(states.set_index("state_code")[["state_name", "region"]])
            .sort_values("late_rate", ascending=False))
by_region = (orders.merge(states, left_on="customer_state", right_on="state_code")
             .groupby("region").agg(orders=("order_id", "size"), late_rate=("is_late", "mean"),
                                    avg_score=("review_score", "mean")).sort_values("late_rate", ascending=False))

# ---- Markdown ----------------------------------------------------------------------------
def table(df, fmts):
    cols = list(df.columns)
    lines = ["| " + " | ".join([df.index.name or ""] + cols) + " |", "|" + "---|" * (len(cols) + 1)]
    for idx, row in df.iterrows():
        lines.append("| " + " | ".join([str(idx)] + [fmts.get(c, "{}").format(row[c]) for c in cols]) + " |")
    return "\n".join(lines)

md = ["# Reference numbers", "",
      "Use these to check the Power BI report. With **no slicers applied**, every card and chart should show",
      "exactly these values. If a number differs, the usual causes are a wrong relationship direction, a measure",
      "that averages over the wrong table, or a slicer left on.", "",
      "Generated by `analysis/reference_numbers.py` from `data/model/`.", "",
      "## KPI cards", "", "| Measure | Value |", "|---|---|"]
md += [f"| {n} | {fmt(n, v)} |" for n, v in k.items()]
md += [f"| Revenue (item price, BRL) | {revenue:,.2f} |", "",
       "## Review score by delivery timing", "",
       table(by_bucket, {"orders": "{:,.0f}", "avg_score": "{:.2f}", "negative_rate": "{:.1%}"}), "",
       "## Late delivery rate by month (purchase month)", "",
       table(by_month, {"orders": "{:,.0f}", "late_rate": "{:.1%}", "avg_score": "{:.2f}"}), "",
       "## By customer region", "",
       table(by_region, {"orders": "{:,.0f}", "late_rate": "{:.1%}", "avg_score": "{:.2f}"}), "",
       "## By customer state", "",
       table(by_state[["state_name", "region", "orders", "late_orders", "late_rate", "avg_delivery_days", "avg_score"]],
             {"orders": "{:,.0f}", "late_orders": "{:,.0f}", "late_rate": "{:.1%}",
              "avg_delivery_days": "{:.1f}", "avg_score": "{:.2f}"}), ""]
(ROOT / "powerbi" / "reference_numbers.md").write_text("\n".join(md))

# ---- Preview charts (same colours as the Power BI theme) -----------------------------------
ON_TIME, LATE = "#2a78d6", "#eb6834"
INK, INK2, MUTED, GRID, AXIS, SURFACE = "#0b0b0b", "#52514e", "#898781", "#e1e0d9", "#c3c2b7", "#fcfcfb"
plt.rcParams.update({
    "figure.facecolor": SURFACE, "axes.facecolor": SURFACE, "savefig.facecolor": SURFACE,
    "font.family": "DejaVu Sans", "font.size": 10.5, "text.color": INK,
    "axes.edgecolor": AXIS, "axes.labelcolor": INK2, "axes.titlesize": 13, "axes.titleweight": "bold",
    "axes.titlelocation": "left", "axes.titlepad": 28, "axes.spines.top": False, "axes.spines.right": False,
    "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.8,
    "xtick.color": MUTED, "ytick.color": MUTED, "xtick.labelcolor": INK2, "ytick.labelcolor": INK2,
    "legend.frameon": False, "savefig.dpi": 200, "savefig.bbox": "tight",
})
def subtitle(ax, text):
    ax.text(0, 1.02, text, transform=ax.transAxes, color=INK2, fontsize=10, va="bottom")

# 1. Review score by delivery timing
fig, ax = plt.subplots(figsize=(8.5, 4.2))
x = np.arange(len(by_bucket))
colors = [LATE if "late" in b else ON_TIME for b in by_bucket.index]
bars = ax.bar(x, by_bucket.avg_score, width=0.62, color=colors, zorder=3)
for b, v in zip(bars, by_bucket.avg_score):
    ax.text(b.get_x() + b.get_width() / 2, v + 0.07, f"{v:.1f}", ha="center", color=INK2)
ax.set_xticks(x, [b.replace(" days", "\ndays").replace(" day", "\nday") for b in by_bucket.index])
ax.set_ylim(0, 5)
ax.grid(axis="x", visible=False)
ax.set_ylabel("Average review score (1–5 stars)")
ax.legend([plt.Rectangle((0, 0), 1, 1, color=c) for c in (ON_TIME, LATE)], ["Delivered by promised date", "Late"],
          loc="upper right", ncol=1)
ax.set_title("Ratings collapse as soon as an order arrives late")
subtitle(ax, "Average review score by delivery date vs. the date promised at checkout")
fig.savefig(IMG / "01_score_by_delivery_timing.png"); plt.close(fig)

# 2. Late rate by month
fig, ax = plt.subplots(figsize=(8.5, 4))
m = by_month.copy(); m.index = m.index.to_timestamp()
ax.plot(m.index, m.late_rate * 100, color=LATE, lw=2, marker="o", markersize=5, zorder=3)
for label, when in [("Black Friday\nNov 2017", "2017-11-01"), ("Feb–Mar 2018", "2018-03-01")]:
    v = m.loc[when, "late_rate"] * 100
    ax.annotate(label, (pd.Timestamp(when), v), xytext=(0, 12), textcoords="offset points",
                ha="center", color=INK2, fontsize=9.5)
ax.yaxis.set_major_formatter(mtick.PercentFormatter(decimals=0))
ax.set_ylim(0, 25)
ax.set_ylabel("Orders delivered late")
ax.set_title("Late deliveries spiked twice: Black Friday 2017 and Feb–Mar 2018")
subtitle(ax, "Share of orders delivered after the promised date, by purchase month")
fig.autofmt_xdate(rotation=0, ha="center")
import matplotlib.dates as mdates
ax.xaxis.set_major_locator(mdates.MonthLocator(bymonth=[1, 4, 7, 10]))
ax.xaxis.set_major_formatter(mdates.DateFormatter("%b\n%Y"))
fig.savefig(IMG / "02_late_rate_by_month.png"); plt.close(fig)

# 3. Late rate by state (states with 300+ orders)
s = by_state[by_state.orders >= 300].sort_values("late_rate")
fig, ax = plt.subplots(figsize=(8.5, 6.4))
y = np.arange(len(s))
ax.barh(y, s.late_rate * 100, height=0.62, color=ON_TIME, zorder=3)
for yi, (v, n) in enumerate(zip(s.late_rate * 100, s.orders)):
    ax.text(v + 0.3, yi, f"{v:.0f}%  ·  {n:,} orders", va="center", color=INK2, fontsize=9)
ax.set_yticks(y, [f"{n} ({c})" for c, n in zip(s.index, s.state_name)])
ax.xaxis.set_major_formatter(mtick.PercentFormatter(decimals=0))
ax.set_xlim(0, 30)
ax.grid(axis="y", visible=False)
ax.set_xlabel("Orders delivered late")
ax.set_title("Late parcels are most common in the Northeast — and in Rio de Janeiro")
subtitle(ax, "Late delivery rate by customer state (states with 300+ orders)")
fig.savefig(IMG / "03_late_rate_by_state.png"); plt.close(fig)

print("\n".join(md[:30]))
print(by_region)
